#Time Filing for long term and returns for shorts

def mix_filling(Y_temp_df,temp_df_filled,ret_df_filled,depth=5,gap_th = 10):

    #Select Layer

    if depth==5:
        Depth_idx='soil_temp_deg_C_at_5_cm_depth'
        neurons=10
    elif depth==20:
        Depth_idx='soil_temp_deg_C_at_20_cm_depth'
        neurons=11
    elif depth==50:
        Depth_idx='soil_temp_deg_C_at_50_cm_depth'
        neurons=12
    elif depth==100:
        Depth_idx='soil_temp_deg_C_at_100_cm_depth'
        neurons=13
    else:
        return "Invalid depth: 5, 20, 50 or 100"

    Y = Y_temp_df[Depth_idx]

    #gap detection

    gap_mask = Y.isna()

    groups = (
        gap_mask != gap_mask.shift()
    ).cumsum()

    gap_sizes = (
        gap_mask.groupby(groups)
        .transform("sum")
    )

    #Mask

    short_gap_mask = (
        gap_mask &
        (gap_sizes <= gap_th)
    )

    long_gap_mask = (
        gap_mask &
        (gap_sizes > gap_th)
    )

    #Final Temp

    temp_final = Y.copy()

    #Short Gaps

    temp_final.loc[short_gap_mask] = (
        ret_df_filled.loc[short_gap_mask]

    )

    #Long Gaps

    temp_final.loc[long_gap_mask] = (
        temp_df_filled.loc[long_gap_mask]
    )

    return temp_final



