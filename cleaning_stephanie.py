#Repeated Values Using Percentil

def repeated_values(df,eps=1e-4,percentil=.99):

    df_clean_stuck = df.copy()
    for col in df_clean_stuck.columns:

      s = df_clean_stuck[col]

      change = s.diff().abs() > eps
      groups = change.cumsum()

      run_length = s.groupby(groups).transform("size")

      # distribución propia
      lengths = run_length.dropna()

      th = lengths.quantile(percentil)

      mask = run_length > th

      df_clean_stuck.loc[mask, col] = np.nan

    return df_clean_stuck

#Returns

def conditional_returns(df, th=3,low=0.001,up=0.999):
    result = pd.DataFrame(index=df.index)

    for col in df.columns:

        s = df[col]

        # Consecutuve gaps size
        gap_sizes = s.isna().groupby((~s.isna()).cumsum()).transform("sum")

        returns = pd.Series(np.nan, index=s.index)

        last_valid_value = None
        gap_count = 0

        for i in range(len(s)):

            val = s.iloc[i]

            if pd.isna(val):
                gap_count += 1
                continue

            # Firs value not NaN
            if last_valid_value is None:
                last_valid_value = val
                gap_count = 0
                continue

            # If gap <= th
            if gap_count <= th:
                # Net return
                returns.iloc[i] = val - last_valid_value
                #Proportion return
                #returns.iloc[i] = (val / last_valid_value) - 1

            # If gap >= th
            else:
                returns.iloc[i] = np.nan

            last_valid_value = val
            gap_count = 0

        result[col] = returns

    # percentile by columns
    lower = result.quantile(low)   # 0.1%
    upper = result.quantile(up)   # 99.9%
    returns_per_clean = result.mask((result < lower) | (result > upper))

    return result, returns_per_clean


