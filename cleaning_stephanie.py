def soil_temp_percentil_neighborhood_outliers_fix_jump(df,low=0.001,up=0.999,th_returns=3,sens_stuck=20,segment_th = 20):

    variables = df.columns.values

    returns,returns_per_clean=conditional_returns(df,th_returns)
    df_Clean_per = df.copy()

    # percentile by columns
    lower = returns.quantile(low)   # 0.1%
    upper = returns.quantile(up)   # 99.9%

    # outliers
    outlier_mask = (returns < lower) | (returns > upper)

    # STUCK SENSOR

    mask_stuck = pd.DataFrame(
        False,
        index=returns.index,
        columns=returns.columns
    )

    for col in returns.columns:

        diff = returns[col].diff().abs()

        stuck = diff < 1e-6

        groups = (stuck != stuck.shift()).cumsum()

        run_length = stuck.groupby(groups).transform("sum")

        mask_stuck[col] = run_length >= sens_stuck

    # Neighborhood

    mask_transient = pd.DataFrame(
        False,
        index=df.index,
        columns=df.columns
    )

    for col in df.columns:

        s = df[col]

        # diferencias
        diff = s.diff()

        # jumps positivos y negativos
        pos_jump = diff > upper[col]
        neg_jump = diff < lower[col]

        pos_idx = np.where(pos_jump)[0]
        neg_idx = np.where(neg_jump)[0]

        # revisar pares
        for p in pos_idx:

            # negativos posteriores cercanos
            nearby_neg = neg_idx[
                (neg_idx > p) &
                (neg_idx - p <= segment_th)
            ]

            if len(nearby_neg) > 0:

                n = nearby_neg[0]

                # eliminar segmento completo
                mask_transient.iloc[p:n+1,
                                    mask_transient.columns.get_loc(col)] = True

        # también al revés
        for n in neg_idx:

            nearby_pos = pos_idx[
                (pos_idx > n) &
                (pos_idx - n <= segment_th)
            ]

            if len(nearby_pos) > 0:

                p = nearby_pos[0]

                mask_transient.iloc[n:p+1,
                                    mask_transient.columns.get_loc(col)] = True

    # FINAL MASK

    final_mask = (
        mask_stuck |
        outlier_mask |
        mask_transient
    )

    # apply mask to temperatures
    df_Clean_per[variables] = (
        df_Clean_per[variables]
        .mask(final_mask)
    )

    return df_Clean_per, returns_per_clean

