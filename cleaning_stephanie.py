#Zscores Outliers neighborhood Using Zscore Dynamic Jump Lenght

def soil_temp_zscores_neighborhood_outliers(
    df,
    zscr_sd=3,
    th_returns=3,
    sens_stuck=20,
    segment_th=20
):

    variables = df.columns.values

    df_clean = df.copy()

    # RETURNS

    returns, returns_per_clean = conditional_returns(df, th_returns)

    # Z-SCORE GLOBAL (solo referencia para detectar vecindades)

    mean_ret = returns.mean()
    std_ret = returns.std()

    z_temp = (returns - mean_ret) / std_ret

    # outliers por z-score (secundario)
    zscore_mask = z_temp.abs() > zscr_sd*std_ret

    # STUCK SENSOR

    mask_stuck = pd.DataFrame(False, index=returns.index, columns=returns.columns)

    for col in returns.columns:

        diff = returns[col].diff().abs()

        stuck = diff < 1e-6

        groups = (stuck != stuck.shift()).cumsum()

        run_length = stuck.groupby(groups).transform("sum")

        mask_stuck[col] = run_length >= sens_stuck

    # CHANGE POINT + SEGMENT DETECTION (NUEVO CORE)

    mask_transient = pd.DataFrame(False, index=returns.index, columns=returns.columns)

    for col in returns.columns:

        r = returns[col]

        # diferencias (detecta saltos reales)
        diff = r.diff().abs()

        # umbral dinámico robusto
        threshold = np.nanpercentile(diff.dropna(), 99)

        jump = diff > threshold

        # expandir vecindad del salto (captura bloques largos)
        expanded = jump.copy()

        for i in range(1, segment_th + 1):
            expanded |= jump.shift(i, fill_value=False)
            expanded |= jump.shift(-i, fill_value=False)

        # incluir NaNs dentro del bloque (CLAVE para tu caso)
        expanded |= r.isna().rolling(segment_th, min_periods=1).max().astype(bool)

        mask_transient[col] = expanded.fillna(False)

    # FINAL MASK

    final_mask = (
        mask_stuck |
        zscore_mask |
        mask_transient
    )

    df_clean[variables] = df_clean[variables].mask(final_mask)

    return df_clean, returns_per_clean


