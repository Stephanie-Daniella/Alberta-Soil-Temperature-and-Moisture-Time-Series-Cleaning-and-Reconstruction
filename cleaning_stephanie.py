# Percentile Outliers Neighborhood Using Dynimic Jump Lenght

def soil_temp_percentil_neighborhood_outliers(
    df,
    low=0.001,
    up=0.999,
    th_returns=3,
    sens_stuck=20,
    segment_th=20
):

    variables = df.columns.values

    returns, returns_per_clean = conditional_returns(df, th_returns)

    df_clean_per = df.copy()

    # Percentile Outliers

    lower = returns.quantile(low)
    upper = returns.quantile(up)

    outlier_mask = (
        (returns < lower) |
        (returns > upper)
    )

    # STUCK SENSOR

    mask_stuck = pd.DataFrame(
        False,
        index=returns.index,
        columns=returns.columns
    )

    for col in returns.columns:

        diff = returns[col].diff().abs()

        stuck = diff < 1e-6

        groups = (stuck != stuck.shift()).cumsum()

        run_length = stuck.groupby(groups).transform("sum")

        mask_stuck[col] = run_length >= sens_stuck

    # CHANGE-POINT NEIGHBORHOODS

    mask_transient = pd.DataFrame(
        False,
        index=returns.index,
        columns=returns.columns
    )

    for col in returns.columns:

        r = returns[col]

        # diferencias absolutas
        diff = r.diff().abs()

        # threshold robusto usando percentil
        jump_threshold = np.nanpercentile(
            diff.dropna(),
            99
        )

        # jumps grandes
        jump = diff > jump_threshold

        # expandir alrededor del jump
        expanded = jump.copy()

        for i in range(1, segment_th + 1):

            expanded |= jump.shift(i, fill_value=False)

            expanded |= jump.shift(-i, fill_value=False)

        # incluir NaNs dentro del segmento
        nan_regions = (
            r.isna()
            .rolling(segment_th, min_periods=1)
            .max()
            .astype(bool)
        )

        expanded |= nan_regions

        mask_transient[col] = expanded.fillna(False)

    # FINAL MASK

    final_mask = (
        outlier_mask |
        mask_stuck |
        mask_transient
    )

    # apply mask
    df_clean_per[variables] = (
        df_clean_per[variables]
        .mask(final_mask)
    )

    return df_clean_per, returns_per_clean


